#!/usr/bin/env python3
"""Operator-only HTTPS smoke test; token values never reach stdout or argv.

Run with sudo on production after deploying. Creates two named verification users,
revokes their short-lived tokens and tombstones the test game even on failure.
The test user records remain for audit. Requires a real PCK exported with Godot 4.7.
"""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import urllib.error
import urllib.request


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--pck', required=True)
    parser.add_argument('--origin', required=True, help='Explicit HTTPS origin of your authorized test instance')
    parser.add_argument('--release', default='/opt/game-stop/current')
    parser.add_argument('--env-file', default='/etc/game-stop/server.env')
    args = parser.parse_args()
    if not args.origin.startswith('https://'):
        raise ValueError('HTTPS required')
    env = dict(os.environ)
    # This file is generated by bootstrap with simple KEY=value records. Do not
    # print it or invoke a shell to interpolate its credentials.
    for line in Path(args.env_file).read_text().splitlines():
        if line and not line.startswith('#'):
            key, value = line.split('=', 1)
            env[key] = value.strip('"')

    def admin(*argv):
        result = subprocess.run([args.release + '/server', *argv], env=env,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if result.returncode:
            raise RuntimeError('administrator command failed (output suppressed)')
        return json.loads(result.stdout) if result.stdout.strip() else None

    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *a, **kw):
            return None
    opener = urllib.request.build_opener(NoRedirect())

    def request(method, path, token=None, data=None, headers=None, expected=200):
        headers = dict(headers or {})
        if token:
            headers['Authorization'] = 'Bearer ' + token
        req = urllib.request.Request(args.origin + path, data=data, headers=headers, method=method)
        try:
            response = opener.open(req, timeout=60)
        except urllib.error.HTTPError as e:
            response = e
        with response:
            body = response.read()
            if response.status != expected:
                raise AssertionError(f'{method} {path}: expected {expected}, got {response.status}')
            return body, response.headers

    suffix = str(time.time_ns())
    game_id = 'verify-' + suffix
    path = '/api/v1/games/' + game_id
    issued = []
    published = False
    owner = None
    try:
        for role in ('owner', 'outsider'):
            name = 'verify-' + role + '-' + suffix
            admin('users', 'create', '--name', name)
            issued.append(admin('tokens', 'create', '--user', name, '--ttl', '10m'))
        owner, outsider = (t['token'] for t in issued)
        pck = Path(args.pck).read_bytes()
        metadata = {'title': 'Deployment verification', 'engine': {'name': 'godot', 'version': '4.7'}, 'visibility': 'private'}
        body, _ = request('PUT', path, owner, pck, {
            'Content-Type': 'application/octet-stream',
            'X-Game-Metadata': base64.b64encode(json.dumps(metadata).encode()).decode()}, 201)
        published = True
        receipt = json.loads(body)
        assert receipt['package']['sha256'] == hashlib.sha256(pck).hexdigest()
        assert receipt['package']['size'] == len(pck)
        request('GET', path, expected=404)
        request('GET', path, outsider, expected=404)
        request('GET', path + '/package.pck', outsider, expected=404)
        request('PATCH', path, outsider, b'{"visibility":"public"}', {'Content-Type': 'application/json'}, 409)
        catalog, _ = request('GET', '/gamesource/v1/index.json')
        assert game_id not in [g['id'] for g in json.loads(catalog)['games']]
        data, headers = request('GET', path + '/package.pck', owner, headers={'Range': 'bytes=0-15'}, expected=206)
        assert data == pck[:16] and headers['Content-Range'].startswith('bytes 0-15/')
        request('PATCH', path, owner, b'{"visibility":"public"}', {'Content-Type': 'application/json'})
        catalog, headers = request('GET', '/gamesource/v1/index.json')
        assert game_id in [g['id'] for g in json.loads(catalog)['games']]
        request('GET', '/gamesource/v1/index.json', headers={'If-None-Match': headers['ETag']}, expected=304)
        data, _ = request('GET', path + '/package.pck')
        assert data == pck
        with tempfile.TemporaryDirectory(prefix='game-stop-verify-') as tmp:
            output = str(Path(tmp) / 'download.pck')
            cli_env = dict(os.environ, GAMESTOP_TOKEN=owner)
            metadata_file = Path(tmp) / 'metadata.json'
            metadata_file.write_text(json.dumps(metadata))
            result = subprocess.run([args.release + '/gamestop', 'upload', '--server', args.origin,
                                     '--id', game_id, '--file', args.pck, '--metadata', str(metadata_file)],
                                    env=cli_env, capture_output=True)
            assert result.returncode == 0, 'CLI upload failed (output suppressed)'
            result = subprocess.run([args.release + '/gamestop', 'download', '--server', args.origin,
                                     '--id', game_id, '--file', output], env=cli_env, capture_output=True)
            assert result.returncode == 0, 'CLI download failed (output suppressed)'
            assert Path(output).read_bytes() == pck
        request('PATCH', path, owner, b'{"visibility":"private"}', {'Content-Type': 'application/json'})
        request('GET', path + '/package.pck', expected=404)
        admin('tokens', 'revoke', '--id', issued[1]['id'])
        request('GET', '/api/v1/games', outsider, expected=401)
        print('PASS: real PCK, ownership, private/public transitions, SHA256, Range, ETag, CLI upload/download, token revocation')
    finally:
        try:
            if published and owner:
                request('DELETE', path, owner, expected=204)
        finally:
            for token in issued:
                # Repeated revocation is allowed; no raw token is logged.
                admin('tokens', 'revoke', '--id', token['id'])
        print('Cleanup: verification game tombstoned and temporary tokens revoked; verification users retained for audit')


if __name__ == '__main__':
    main()
